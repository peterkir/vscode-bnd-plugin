import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

export interface LockInfo {
    pid?: number;
    host?: string;
    user?: string;
}

export interface EclipseInstance {
    workspaceRoot: string;
    pid: number;
    host?: string;
    user?: string;
}

export interface EclipseProbes {
    isAlive?: (pid: number) => boolean;
    hostname?: string;
}

/** A definition of an output directory key. `file` is relative to the workspace root, with forward slashes. */
export interface OutputOverride {
    file: string;
    line: number;
    key: string;
}

export interface TwinInspection {
    configured: boolean;
    workspaceOverrides: OutputOverride[];
    projectOverrides: OutputOverride[];
    /** `.bndrun` files, relative to the workspace root, whose storage directory follows neither the driver nor the target directory. */
    sharedLaunchStorage: string[];
    /** `.classpath` files of Eclipse projects, relative to the workspace root, that carry the container an earlier Java project import wrote. */
    staleClasspaths: string[];
}

export interface ConfigureTwinResult {
    file: string;
    written: boolean;
    refused: boolean;
    workspaceOverrides: OutputOverride[];
}

export interface EclipseWorkspaceState {
    instance: EclipseInstance;
    configured: boolean;
}

export interface EclipseStatusPresentation {
    visible: boolean;
    text: string;
    tooltip: string;
    warning: boolean;
}

export const twinConfigurationPath = 'cnf/ext/vscode-outputs.bnd';

export const twinOutputDirectories = ['bin.vscode', 'bin_test.vscode', 'generated.vscode'];

export const twinConfigurationContent = [
    '# Generated by the bnd VS Code extension (bnd: Configure Parallel Use with Eclipse).',
    '# Gives VS Code its own compiler and bundle output next to the Eclipse output.',
    "# The bnd language server and the Java project import report the driver 'vscode';",
    '# Eclipse Bndtools, the bnd CLI and Gradle keep bin, bin_test and generated.',
    'vscode.outputs: ${if;${driver;vscode};.vscode}',
    'bin: bin${vscode.outputs}',
    'testbin: bin_test${vscode.outputs}',
    'target-dir: generated${vscode.outputs}',
    '',
].join('\n');

const outputKey = /^(bin|testbin|target-dir)[ \t]*[:=]/;
const label = 'Eclipse';
// Written to .classpath by the Java project import of extension versions before 0.28.0; Eclipse cannot resolve it.
const jdtlsContainerEntry = /^[ \t]*<classpathentry\s+kind="con"\s+path="org\.bndtools\.jdtls\.BND_CONTAINER"\s*\/>[ \t]*\r?\n/m;
const bndtoolsNature = 'bndtools.core.bndnature';

function unescapeProperty(text: string): string {
    return text.replace(/\\(u[0-9a-fA-F]{4}|.)/g, (_match, escaped: string) => {
        if (escaped.length === 5) return String.fromCharCode(parseInt(escaped.slice(1), 16));
        switch (escaped) {
            case 't': return '\t';
            case 'n': return '\n';
            case 'r': return '\r';
            case 'f': return '\f';
            default: return escaped;
        }
    });
}

function parseProperties(text: string): Map<string, string> {
    const properties = new Map<string, string>();
    for (const raw of text.split(/\r?\n/)) {
        const line = raw.trim();
        if (!line || line.startsWith('#') || line.startsWith('!')) continue;
        const match = /^((?:\\.|[^\\:=\s])*)\s*[:=]?\s*(.*)$/.exec(line);
        if (!match || !match[1]) continue;
        properties.set(unescapeProperty(match[1]), unescapeProperty(match[2]).trim());
    }
    return properties;
}

export function parseLockInfo(text: string): LockInfo {
    const properties = parseProperties(text);
    const info: LockInfo = {};
    const processId = properties.get('process-id') ?? '';
    const pid = /^\d+$/.test(processId) ? Number(processId) : NaN;
    if (Number.isSafeInteger(pid) && pid > 0) info.pid = pid;
    const host = properties.get('host');
    if (host) info.host = host;
    const user = properties.get('user');
    if (user) info.user = user;
    return info;
}

export function isProcessAlive(pid: number): boolean {
    try {
        process.kill(pid, 0);
        return true;
    } catch (error) {
        // EPERM: the process exists but belongs to another user.
        return (error as NodeJS.ErrnoException)?.code === 'EPERM';
    }
}

function shortHostName(host: string): string {
    return host.split('.')[0].toLowerCase();
}

/**
 * Eclipse leaves `.metadata/.lock_info` behind when it exits, so the recorded process must be alive.
 * Only covers an Eclipse workspace located in the bnd workspace root.
 */
export function detectEclipse(workspaceRoot: string, probes: EclipseProbes = {}): EclipseInstance | undefined {
    try {
        const info = parseLockInfo(fs.readFileSync(path.join(workspaceRoot, '.metadata', '.lock_info'), 'utf8'));
        if (info.pid === undefined) return undefined;
        if (info.host && shortHostName(info.host) !== shortHostName(probes.hostname ?? os.hostname())) return undefined;
        if (!(probes.isAlive ?? isProcessAlive)(info.pid)) return undefined;
        return { workspaceRoot, pid: info.pid, ...(info.host ? { host: info.host } : {}), ...(info.user ? { user: info.user } : {}) };
    } catch {
        return undefined;
    }
}

export function twinConfigurationFile(workspaceRoot: string): string {
    return path.join(workspaceRoot, ...twinConfigurationPath.split('/'));
}

export function isTwinConfigured(workspaceRoot: string): boolean {
    try {
        return fs.statSync(twinConfigurationFile(workspaceRoot)).isFile();
    } catch {
        return false;
    }
}

function readText(file: string): string | undefined {
    try {
        return fs.readFileSync(file, 'utf8');
    } catch {
        return undefined;
    }
}

function listEntries(directory: string): fs.Dirent[] {
    try {
        return fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
    } catch {
        return [];
    }
}

function outputOverrides(workspaceRoot: string, relative: string): OutputOverride[] {
    const text = readText(path.join(workspaceRoot, ...relative.split('/')));
    if (text === undefined) return [];
    const overrides: OutputOverride[] = [];
    text.split(/\r?\n/).forEach((line, index) => {
        const match = outputKey.exec(line);
        if (match) overrides.push({ file: relative, line: index + 1, key: match[1] });
    });
    return overrides;
}

// The target directory follows the driver once the twin configuration exists.
function sharesLaunchStorage(text: string): boolean {
    const effective = text.split(/\r?\n/).filter(line => !/^\s*[#!]/.test(line)).join('\n');
    return !effective.includes('${driver') && !effective.includes('${target-dir}')
        && (/^-runstorage[ \t]*[:=]/m.test(effective) || /launch\.storage\.dir[ \t]*[:=]/.test(effective));
}

export function inspectTwinConfiguration(workspaceRoot: string): TwinInspection {
    const generated = path.posix.basename(twinConfigurationPath);
    const workspaceOverrides = outputOverrides(workspaceRoot, 'cnf/build.bnd');
    for (const entry of listEntries(path.join(workspaceRoot, 'cnf', 'ext'))) {
        if (entry.isFile() && entry.name.endsWith('.bnd') && entry.name !== generated) {
            workspaceOverrides.push(...outputOverrides(workspaceRoot, `cnf/ext/${entry.name}`));
        }
    }
    const projectOverrides: OutputOverride[] = [];
    const sharedLaunchStorage: string[] = [];
    const staleClasspaths: string[] = [];
    for (const directory of listEntries(workspaceRoot)) {
        if (!directory.isDirectory() && !directory.isSymbolicLink()) continue;
        if (directory.name !== 'cnf') projectOverrides.push(...outputOverrides(workspaceRoot, `${directory.name}/bnd.bnd`));
        if (hasStaleClasspath(path.join(workspaceRoot, directory.name))) staleClasspaths.push(`${directory.name}/.classpath`);
        for (const entry of listEntries(path.join(workspaceRoot, directory.name))) {
            if (!entry.isFile() || !entry.name.endsWith('.bndrun')) continue;
            const text = readText(path.join(workspaceRoot, directory.name, entry.name));
            if (text !== undefined && sharesLaunchStorage(text)) sharedLaunchStorage.push(`${directory.name}/${entry.name}`);
        }
    }
    return { configured: isTwinConfigured(workspaceRoot), workspaceOverrides, projectOverrides, sharedLaunchStorage, staleClasspaths };
}

// Only projects that Eclipse Bndtools manages; other .classpath files belong to the Java project import.
function hasStaleClasspath(project: string): boolean {
    return (readText(path.join(project, '.project')) ?? '').includes(bndtoolsNature)
        && jdtlsContainerEntry.test(readText(path.join(project, '.classpath')) ?? '');
}

/** Removes the Java project import's container from the `.classpath` of Eclipse projects. Returns the changed files, relative to the workspace root. */
export function removeStaleClasspathEntries(workspaceRoot: string): string[] {
    const changed: string[] = [];
    for (const relative of inspectTwinConfiguration(workspaceRoot).staleClasspaths) {
        const file = path.join(workspaceRoot, ...relative.split('/'));
        const text = readText(file);
        if (text === undefined) continue;
        fs.writeFileSync(file, text.replace(jdtlsContainerEntry, ''), 'utf8');
        changed.push(relative);
    }
    return changed;
}

/** Writes nothing while `bin`, `testbin`, or `target-dir` are defined elsewhere in the workspace configuration. */
export function configureTwin(workspaceRoot: string): ConfigureTwinResult {
    const file = twinConfigurationFile(workspaceRoot);
    const { workspaceOverrides } = inspectTwinConfiguration(workspaceRoot);
    if (workspaceOverrides.length) return { file, written: false, refused: true, workspaceOverrides };
    if (readText(file) === twinConfigurationContent) return { file, written: false, refused: false, workspaceOverrides };
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, twinConfigurationContent, 'utf8');
    return { file, written: true, refused: false, workspaceOverrides };
}

export function removeTwin(workspaceRoot: string): boolean {
    const file = twinConfigurationFile(workspaceRoot);
    if (!fs.existsSync(file)) return false;
    fs.rmSync(file, { force: true });
    return true;
}

export function formatOverride(override: OutputOverride): string {
    return `${override.file}:${override.line} (${override.key})`;
}

export function eclipseDetectedMessage(instance: EclipseInstance): string {
    return `Eclipse (pid ${instance.pid}) has the bnd workspace ${path.basename(instance.workspaceRoot)} open. `
        + 'VS Code and Eclipse write the same build output.';
}

export function presentEclipseStatus(states: EclipseWorkspaceState[]): EclipseStatusPresentation {
    if (!states.length) {
        return { visible: false, text: `$(link) ${label}`, tooltip: 'No Eclipse instance detected on an open bnd workspace.', warning: false };
    }
    const warning = states.some(state => !state.configured);
    const lines = states.map(state => `Eclipse (pid ${state.instance.pid}) has this bnd workspace open: ${state.instance.workspaceRoot}. `
        + (state.configured
            ? `VS Code uses separate output directories (${twinOutputDirectories.join(', ')}).`
            : 'VS Code and Eclipse write the same build output.'));
    return {
        visible: true,
        text: `$(${warning ? 'warning' : 'link'}) ${label}`,
        tooltip: `${lines.join('\n')} Click for options.`,
        warning,
    };
}
